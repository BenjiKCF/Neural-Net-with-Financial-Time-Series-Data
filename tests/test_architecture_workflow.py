"""Actual Qlib training, export, and fitted-preprocessor replay for every mini."""

import json
import pickle
from pathlib import Path

import numpy as np
import pandas as pd
import pytest
import yaml

from financial_ts.catalog import MINI_ARCHITECTURES
from financial_ts.data import create_demo_csv, import_csv
from financial_ts.workflow import run_workflow

pytestmark = pytest.mark.integration


@pytest.fixture(scope="module")
def architecture_provider(tmp_path_factory):
    root = tmp_path_factory.mktemp("architecture-market")
    source = create_demo_csv(root / "synthetic.csv", n_instruments=2, n_days=160)
    provider = root / "provider"
    metadata = import_csv(source, provider)
    metadata["synthetic"] = True
    (provider / "metadata.json").write_text(json.dumps(metadata), encoding="utf-8")
    return provider


@pytest.mark.parametrize("name", list(MINI_ARCHITECTURES))
def test_mini_workflow_trains_exports_and_replays_without_refitting(
    name, architecture_provider, tmp_path, monkeypatch
):
    pytest.importorskip("torch")
    import qlib
    from qlib.data.dataset.handler import DataHandlerLP
    from qlib.data.dataset.processor import RobustZScoreNorm

    from financial_ts.model import SequenceForecastModel

    output = tmp_path / name
    result = run_workflow(
        {
            "provider_uri": str(architecture_provider),
            "output_dir": str(output),
            "experiment_name": "mini_integration",
            "region": "us",
            "instruments": "all",
            "seed": 42,
            "sequence_length": 32,
            "model": {
                "name": name,
                "params": {
                    "d_model": 16,
                    "nhead": 2,
                    "num_layers": 1,
                    "n_epochs": 1,
                    "early_stop": 1,
                    "batch_size": 64,
                    "dropout": 0,
                    "device": "cpu",
                    "num_threads": 2,
                    "aux_loss_weight": 0.01,
                },
            },
            "backtest": {"enabled": False},
        }
    )

    predictions = pd.read_csv(output / "predictions.csv", parse_dates=["datetime"])
    predictions = predictions.set_index(["datetime", "instrument"]).sort_index()
    assert predictions.index.is_unique
    assert np.isfinite(predictions[["score", "label"]].to_numpy()).all()
    calendar = pd.DatetimeIndex(
        pd.to_datetime((architecture_provider / "calendars/day.txt").read_text().splitlines())
    )
    start, end = result["run"]["segments"]["test"]
    dates = calendar[(calendar >= start) & (calendar <= end)]
    expected_index = pd.MultiIndex.from_product(
        [dates, ["DEMO000", "DEMO001"]], names=["datetime", "instrument"]
    )
    pd.testing.assert_index_equal(predictions.index, expected_index)
    assert (
        result["metrics"]["prediction_count"]
        == result["metrics"]["evaluated_count"]
        == len(expected_index)
    )
    details = result["metrics"]["model_details"]
    assert details["name"] == name and details["pretrained"] is False
    assert details["parameter_count"] > 0
    assert details["best_epoch"] == details["epochs_run"] == 1
    assert np.isfinite(details["validation_rmse"]) and details["validation_rmse"] >= 0
    assert details["fit_seconds"] > 0
    curves = json.loads((output / "learning_curves.json").read_text())
    assert len(curves["train"]) == len(curves["valid"]) == 1
    assert np.isfinite([curves["train"][0], curves["valid"][0]]).all()
    assert details["validation_rmse"] ** 2 == pytest.approx(curves["valid"][0])
    assert result["run"]["synthetic"] is True
    task = yaml.safe_load((output / "qlib_task.yaml").read_text())["task"]
    assert task["model"]["kwargs"]["aux_loss_weight"] == 0.01

    # Load only artifacts generated by this test, never downloaded pickle files.
    artifact_dir = (
        Path(result["output_dir"])
        / "mlruns"
        / result["run"]["experiment_id"]
        / result["run"]["recorder_id"]
        / "artifacts"
    )
    with (artifact_dir / "params.pkl").open("rb") as stream:
        fitted = pickle.load(stream)
    with (artifact_dir / "dataset").open("rb") as stream:
        dataset = pickle.load(stream)
    with (artifact_dir / "pred.pkl").open("rb") as stream:
        recorded = pickle.load(stream).iloc[:, 0]
    assert isinstance(fitted, SequenceForecastModel)
    assert fitted.architecture == name
    module, expected_class = MINI_ARCHITECTURES[name]
    assert type(fitted.model).__name__ == expected_class
    assert type(fitted.model).__module__ == f"financial_ts.architectures.{module}"
    assert (
        sum(parameter.numel() for parameter in fitted.model.parameters())
        == details["parameter_count"]
    )
    scaler = next(
        processor
        for processor in dataset.handler.infer_processors
        if isinstance(processor, RobustZScoreNorm)
    )
    original_mean, original_scale = scaler.mean_train.copy(), scaler.std_train.copy()

    def forbid_refit(*args, **kwargs):
        pytest.fail("Restoring inference must reuse the fitted feature normalizer")

    monkeypatch.setattr(RobustZScoreNorm, "fit", forbid_refit)
    qlib.init(
        provider_uri=str(architecture_provider),
        region="us",
        kernels=1,
        expression_cache=None,
        dataset_cache=None,
    )
    dataset.setup_data(handler_kwargs={"init_type": DataHandlerLP.IT_LS})
    replayed = fitted.predict(dataset)
    pd.testing.assert_series_equal(replayed, recorded, check_exact=True)
    np.testing.assert_array_equal(scaler.mean_train, original_mean)
    np.testing.assert_array_equal(scaler.std_train, original_scale)
